//! **Important**: You should never use the `data_macros` crate directly.
//! Instead you should only use the reexported macros from the `data_core` crate.
//! Using the `data_core` crate has the benefit that this crate also reexports
//! all crates used by the macros.

use darling::FromDeriveInput;
use proc_macro::TokenStream;
use syn::{DeriveInput, parse_macro_input};

use message::Message;

#[cfg(feature = "can")]
mod can;
mod message;

/// Derive macro for generating a module with type aliases for all enum variants
///
/// **Note**: When using the `#[message(struct_derives = [...])]` attribute, some derives (e.g. `bincode::Encode`) might
/// expand to types starting with `::crate_name` which can only be satisfied when the `crate_name` crate is installed in
/// the crate using this macro.
///
/// **Important**: You can only derive this macro on a single enum per module. The reason for this is that the type aliases
/// are written to the [`message::MESSAGE_META_TYPES_IDENT`] module, which does not contain the enum name in it's name.
///
/// # Usage
/// ```rust
/// #[derive(Message)]
/// // implement `Debug` for the struct which will be generated
/// // for `Variant3`
/// #[message(struct_derives = [Debug])]
/// enum Message {
///     Variant1,
///     Variant2(String),
///     Variant3 { id: String, value: u64 },
/// }
#[proc_macro_derive(Message, attributes(message))]
pub fn derive_message(input: TokenStream) -> TokenStream {
    let input = parse_macro_input!(input as DeriveInput);
    match Message::from_derive_input(&input) {
        Ok(message) => message::handle(message),
        Err(err) => err.write_errors(),
    }
    .into()
}

/// Derive macro for implementing the [`can_hal::Encode`] and [`can_hal::Decode`] traits for the message enum.
///
/// Additionally, it generates a module with a CAN id for every enum variant.
///
/// **Important**: This macro relies on the type aliases generated by the `Message` macro
///
/// **Important**: You can only derive this macro on a single enum per module. The reason for this is that the encode/decode
/// implementations are done in the [`can::encode::CAN_ENCODE_MESSAGE_META_IDENT`] and [`can::decode::CAN_DECODE_MESSAGE_META_IDENT`] module respectively.
/// Both modules don't contain the enum name in their name.
///
/// # Usage
/// ```rust
/// #[derive(Message, CanMessage)]
/// enum Message {
///     #[can(id = 0x01)]
///     Variant1(String),
///     // this variant will be ignored, as it doesn't have an id
///     Variant2,
///     #[can(id = 0x02)]
///     Variant3 { id: String, value: u32 },
/// }
#[cfg(feature = "can")]
#[proc_macro_derive(CanMessage, attributes(can))]
pub fn derive_can_message(input: TokenStream) -> TokenStream {
    use crate::can::message::{CanMessage, handle};

    let input = parse_macro_input!(input as DeriveInput);
    match CanMessage::from_derive_input(&input) {
        Ok(message) => handle(message),
        Err(err) => err.write_errors(),
    }
    .into()
}

/// Derive macro for implementing the [`can_hal::Decode`] trait for the message enum.
///
/// The enum needs to be annotated with one of the two mutually exclusive attributes:
/// - `#[can(sparse)]`: Implement sparse decoding for the message enum. Sparse decoding should not be implemented using
///   this macro directly, instead use the [`sparse_decodable_can_message`] macro.
/// - `#[can(dispatch)]`: Implement dispatch decoding for the message enum. This means that every variant
///   of the enum needs to be a message enum itself. \
///   **Important**: When using the dispatch decoding, it's required that you have the [thiserror](https://crates.io/crates/thiserror) crate
///   available in your current crate
///
/// **Important**: You can only derive this macro on a single enum per module. The reason for this is that the decode
/// implementation is done in the [`can::decode::CAN_DECODE_MESSAGE_META_IDENT`] module.
/// This module doesn't contain the enum name in it's name.
///
/// # Usage
/// ```rust
/// #[derive(CanEncode)]
/// #[can(dispatch)]
/// enum Message {
///     MessageKind1(path::to::message1),
///     MessageKind2(path::to::message2),
/// }
/// ```
#[cfg(feature = "can")]
#[proc_macro_derive(CanDecode, attributes(can))]
pub fn derive_can_decode(input: TokenStream) -> TokenStream {
    use crate::can::decode::{CanDecode, handle};

    let input = parse_macro_input!(input as DeriveInput);
    match CanDecode::from_derive_input(&input) {
        Ok(decode) => handle(decode),
        Err(err) => err.write_errors(),
    }
    .into()
}

